"""PostgreSQL adapter for the existing parameterized SQL repository."""
import os
import re
import sqlite3
from contextlib import contextmanager
import psycopg
from psycopg.rows import dict_row

DB_ERRORS = (sqlite3.Error, psycopg.Error)
INTEGRITY_ERRORS = (sqlite3.IntegrityError, psycopg.IntegrityError)

def database_url():
    return os.getenv("DATABASE_URL", "").strip()

class Row(dict):
    def __getitem__(self, key):
        return tuple(self.values())[key] if isinstance(key, int) else super().__getitem__(key)

class Cursor:
    def __init__(self, cursor, lastrowid=None):
        self.cursor = cursor
        self.lastrowid = lastrowid
        self.rowcount = cursor.rowcount
    def fetchone(self):
        row = self.cursor.fetchone()
        return Row(row) if row is not None else None
    def fetchall(self):
        return [Row(row) for row in self.cursor.fetchall()]
    def __iter__(self):
        return (Row(row) for row in self.cursor)

class Connection:
    def __init__(self, conn):
        self.conn = conn
    def executescript(self, sql):
        sql = sql.replace("INTEGER PRIMARY KEY", "INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY")
        sql = sql.replace(" COLLATE NOCASE", "")
        sql = sql.replace("DEFAULT CURRENT_TIMESTAMP", "DEFAULT (CURRENT_TIMESTAMP AT TIME ZONE 'UTC')::text")
        for statement in sql.split(";"):
            if statement.strip():
                self.conn.execute(statement)
        self.conn.execute("CREATE UNIQUE INDEX IF NOT EXISTS ux_users_email_ci ON users(lower(email))")
        self.conn.execute("CREATE UNIQUE INDEX IF NOT EXISTS ux_categories_name_ci ON categories(lower(name))")
    def execute(self, sql, params=()):
        if sql == "BEGIN IMMEDIATE":
            self.conn.execute("BEGIN")
            return Cursor(self.conn.execute("LOCK TABLE users, categories, products, cart_items, orders, order_items IN SHARE ROW EXCLUSIVE MODE"))
        if sql.startswith("PRAGMA table_info(users)"):
            return Cursor(self.conn.execute("SELECT column_name AS name FROM information_schema.columns WHERE table_schema=current_schema() AND table_name='users'"))
        if sql.startswith("INSERT OR IGNORE"):
            sql = sql.replace("INSERT OR IGNORE", "INSERT", 1) + " ON CONFLICT DO NOTHING"
        sql = sql.replace("?", "%s")
        sql = re.sub(r"\bLIKE\b", "ILIKE", sql)
        if params:
            cursor = self.conn.execute(sql + (" RETURNING id" if re.match(r"\s*INSERT INTO (orders|products)\b", sql, re.I) else ""), params)
        else:
            cursor = self.conn.execute(sql)
        lastrowid = None
        if re.match(r"\s*INSERT INTO (orders|products)\b", sql, re.I):
            lastrowid = cursor.fetchone()["id"]
        return Cursor(cursor, lastrowid)

@contextmanager
def postgres_connect():
    with psycopg.connect(database_url(), autocommit=True, row_factory=dict_row, connect_timeout=10) as conn:
        yield Connection(conn)
